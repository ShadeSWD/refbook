/* rmrs-graph.js — вычислительный каскад Правил РМРС / Кодекса ОСНС.
 *
 * Идея: каждая величина («буква» правил) — узел графа с формулой и
 * зависимостями. Расчёт любой величины автоматически разворачивает дерево
 * зависимостей: известные значения берутся из контекста-судна, остальные
 * вычисляются по своим формулам рекурсивно. Любую величину можно either
 * задать известной (передать в контексте), либо углубиться и посчитать её
 * по правилам дальше.
 *
 *   const ship = { L: 100, B: 16, d: 5.6, Cb: 0.7, zg: 4.8 };
 *   RMRSG.compute('Mw_hog', ship)   → { value, unit, formula, sub, rule,
 *                                       children: [дерево зависимостей] }
 *   RMRSG.quantities()              → список всех величин с описаниями
 *   RMRSG.inputsFor('K_weather')    → какие исходные нужны величине
 *
 * Оцифрованы разделы (наполнение наращивается, структура рассчитана на все
 * тома): ч. II «Корпус» — общий изгиб; Кодекс ОСНС 2008 — качка и критерий
 * погоды (с таблицами X1, X2, k, s); ч. III — рулевое устройство (площадь,
 * баллер); SGISC MSC.1/Circ.1627 — уровень 1. */
(function (root, factory) {
  if (typeof module !== 'undefined' && module.exports) module.exports = factory();
  else root.RMRSG = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  const r = (v, n = 3) => { const p = 10 ** n; return Math.round(v * p) / p; };
  const interp = (table, x) => {
    // кусочно-линейная интерполяция по таблице [[x, y], …] с отсечкой краёв
    if (x <= table[0][0]) return table[0][1];
    for (let i = 1; i < table.length; i++) {
      if (x <= table[i][0]) {
        const [x0, y0] = table[i - 1], [x1, y1] = table[i];
        return y0 + (y1 - y0) * (x - x0) / (x1 - x0);
      }
    }
    return table[table.length - 1][1];
  };

  /* ----- исходные величины (листья; задаются в контексте судна) ----- */
  const INPUTS = {
    L: ['длина судна', 'м'], B: ['ширина', 'м'], d: ['осадка', 'м'],
    H: ['высота борта', 'м'], Cb: ['коэффициент общей полноты', '—'],
    zg: ['аппликата центра тяжести', 'м'], V: ['объёмное водоизмещение', 'м³'],
    GM: ['метацентрическая высота h', 'м'], k_mat: ['коэффициент материала (1/0,78/0,72)', '—'],
    Msw: ['изгибающий момент на тихой воде', 'кН·м'],
    W_deck: ['момент сопротивления по палубе', 'м³'],
    A_par: ['площадь парусности', 'м²'], Z_par: ['плечо парусности', 'м'],
    Ak: ['суммарная площадь скуловых килей', 'м²'],
    P_wind: ['давление ветра (504/353/252 по району)', 'Па'],
    v_kn: ['скорость судна', 'уз'],
    d_TL: ['осадка на подошве волны (SGISC)', 'м'], d_TH: ['осадка на вершине волны', 'м'],
    KB: ['аппликата центра величины', 'м'], I_TL: ['момент инерции ВЛ при d_TL', 'м⁴'],
    I_TH: ['момент инерции ВЛ при d_TH', 'м⁴'],
  };

  /* ----- расчётные величины: id → {title, unit, rule, deps, f, formula, sub} ----- */
  const Q = {};
  const def = (id, title, unit, rule, deps, formula, f, sub) =>
    Q[id] = { id, title, unit, rule, deps, formula, f, sub };

  /* === ч. II «Корпус»: общий продольный изгиб === */
  def('cw', 'волновой коэффициент', '—', 'РМРС ч. II, 1.4.4.1', ['L'],
    'c_w = 0,0856·L (L≤90); 10,75 − ((300−L)/100)^1,5 (90<L≤300)',
    v => v.L <= 90 ? 0.0856 * v.L : v.L <= 300 ? 10.75 - ((300 - v.L) / 100) ** 1.5 : 10.75,
    (v, x) => v.L <= 90 ? `0,0856·${v.L}` : `10,75 − ((300−${v.L})/100)^1,5`);
  def('Mw_hog', 'волновой момент, перегиб', 'кН·м', 'РМРС ч. II, 1.4.4.1 (IACS UR S11)',
    ['cw', 'B', 'L', 'Cb'], 'M_w,пер = 190·c_w·B·L²·C_b·10⁻³',
    v => 190 * v.cw * v.B * v.L ** 2 * Math.max(v.Cb, 0.6) * 1e-3,
    v => `190·${r(v.cw, 2)}·${v.B}·${v.L}²·${v.Cb}·10⁻³`);
  def('Mw_sag', 'волновой момент, прогиб', 'кН·м', 'РМРС ч. II, 1.4.4.1 (IACS UR S11)',
    ['cw', 'B', 'L', 'Cb'], 'M_w,прог = −110·c_w·B·L²·(C_b+0,7)·10⁻³',
    v => -110 * v.cw * v.B * v.L ** 2 * (Math.max(v.Cb, 0.6) + 0.7) * 1e-3,
    v => `−110·${r(v.cw, 2)}·${v.B}·${v.L}²·(${v.Cb}+0,7)·10⁻³`);
  def('M_total_hog', 'расчётный момент, перегиб', 'кН·м', 'РМРС ч. II, 1.4.3',
    ['Msw', 'Mw_hog'], 'M = M_тв + M_w,пер',
    v => v.Msw + v.Mw_hog, v => `${r(v.Msw, 0)} + ${r(v.Mw_hog, 0)}`);
  def('Wmin', 'минимальный момент сопротивления', 'м³', 'РМРС ч. II, 1.4.6.7',
    ['cw', 'B', 'L', 'Cb', 'k_mat'], 'W_min = c_w·B·L²·(C_b+0,7)·k·10⁻⁶',
    v => v.cw * v.B * v.L ** 2 * (Math.max(v.Cb, 0.6) + 0.7) * v.k_mat * 1e-6,
    v => `${r(v.cw, 2)}·${v.B}·${v.L}²·(${v.Cb}+0,7)·${v.k_mat}·10⁻⁶`);
  def('sigma_dop', 'допускаемое напряжение общего изгиба', 'МПа', 'РМРС ч. II, 1.4.6',
    ['k_mat'], 'σ_доп = 175/k', v => 175 / v.k_mat, v => `175/${v.k_mat}`);
  def('sigma_deck', 'напряжение в палубе (перегиб)', 'МПа', 'σ = M/W',
    ['M_total_hog', 'W_deck'], 'σ = M/(W·10³)',
    v => v.M_total_hog / v.W_deck / 1000, v => `${r(v.M_total_hog, 0)}/(${r(v.W_deck, 2)}·10³)`);

  /* === Кодекс ОСНС 2008: качка и критерий погоды === */
  def('C_roll', 'инерционный коэффициент', '—', 'Кодекс ОСНС, 2.3.4',
    ['B', 'd', 'L'], 'C = 0,373 + 0,023·B/d − 0,043·L/100',
    v => 0.373 + 0.023 * v.B / v.d - 0.043 * v.L / 100,
    v => `0,373 + 0,023·${r(v.B / v.d, 2)} − 0,043·${r(v.L / 100, 2)}`);
  def('T_roll', 'период бортовой качки', 'с', 'Кодекс ОСНС, 2.3.4',
    ['C_roll', 'B', 'GM'], 'T = 2·C·B/√h',
    v => 2 * v.C_roll * v.B / Math.sqrt(v.GM),
    v => `2·${r(v.C_roll)}·${v.B}/√${r(v.GM, 2)}`);
  def('X1', 'множитель формы X₁(B/d)', '—', 'Кодекс ОСНС, табл. 2.3.4-1', ['B', 'd'],
    'X₁ — таблица по B/d (2,4→1,00 … 3,5→0,80)',
    v => interp([[2.4, 1.0], [2.5, .98], [2.6, .96], [2.7, .95], [2.8, .93], [2.9, .91],
      [3.0, .90], [3.1, .88], [3.2, .86], [3.4, .82], [3.5, .80]], v.B / v.d),
    v => `B/d = ${r(v.B / v.d, 2)}`);
  def('X2', 'множитель полноты X₂(C_b)', '—', 'Кодекс ОСНС, табл. 2.3.4-2', ['Cb'],
    'X₂ — таблица по C_b (0,45→0,75 … 0,70→1,00)',
    v => interp([[0.45, .75], [0.50, .82], [0.55, .89], [0.60, .95], [0.65, .97], [0.70, 1.0]], v.Cb),
    v => `C_b = ${v.Cb}`);
  def('k_bilge', 'множитель скуловых килей k', '—', 'Кодекс ОСНС, табл. 2.3.4-4',
    ['Ak', 'L', 'B'], 'k — таблица по A_k·100/(L·B)',
    v => interp([[0, 1.0], [1.0, .98], [1.5, .95], [2.0, .88], [2.5, .79], [3.0, .74], [3.5, .72], [4.0, .70]],
      v.Ak * 100 / (v.L * v.B)),
    v => `A_k·100/(L·B) = ${r(v.Ak * 100 / (v.L * v.B), 2)} %`);
  def('r_fact', 'параметр r = 0,73 + 0,6·(z_g − d)/d', '—', 'Кодекс ОСНС, 2.3.4',
    ['zg', 'd'], 'r = 0,73 + 0,6·(z_g − d)/d',
    v => Math.min(1, 0.73 + 0.6 * (v.zg - v.d) / v.d),
    v => `0,73 + 0,6·(${v.zg}−${v.d})/${v.d}`);
  def('s_fact', 'параметр s(T)', '—', 'Кодекс ОСНС, табл. 2.3.4-3', ['T_roll'],
    's — таблица по периоду качки T (6 с→0,100 … 20 с→0,035)',
    v => interp([[6, .100], [7, .098], [8, .093], [12, .065], [14, .053], [16, .044], [18, .038], [20, .035]], v.T_roll),
    v => `T = ${r(v.T_roll, 1)} с`);
  def('theta1', 'амплитуда качки θ₁', 'град', 'Кодекс ОСНС, 2.3.4',
    ['k_bilge', 'X1', 'X2', 'r_fact', 's_fact'], 'θ₁ = 109·k·X₁·X₂·√(r·s)',
    v => 109 * v.k_bilge * v.X1 * v.X2 * Math.sqrt(v.r_fact * v.s_fact),
    v => `109·${r(v.k_bilge, 2)}·${r(v.X1, 2)}·${r(v.X2, 2)}·√(${r(v.r_fact, 2)}·${r(v.s_fact, 3)})`);
  def('lw1', 'плечо статического ветра', 'м', 'Кодекс ОСНС, 2.3.2',
    ['P_wind', 'A_par', 'Z_par', 'V'], 'l_w1 = P·A·Z/(1000·g·ρ·V)',
    v => v.P_wind * v.A_par * v.Z_par / (1000 * 9.81 * 1.025 * v.V),
    v => `${v.P_wind}·${v.A_par}·${v.Z_par}/(1000·9,81·1,025·${v.V})`);
  def('lw2', 'плечо шквала', 'м', 'Кодекс ОСНС, 2.3.2', ['lw1'],
    'l_w2 = 1,5·l_w1', v => 1.5 * v.lw1, v => `1,5·${r(v.lw1, 4)}`);

  /* === ч. III: рулевое устройство === */
  def('A_rud', 'площадь пера руля', 'м²', 'РМРС ч. III, 2.2',
    ['L', 'd', 'B', 'Cb'], 'A = (L·d/100)·(1 + 50·C_b²·(B/L)²)',
    v => (v.L * v.d / 100) * (1 + 50 * v.Cb ** 2 * (v.B / v.L) ** 2),
    v => `(${v.L}·${v.d}/100)·(1 + 50·${v.Cb}²·(${r(v.B / v.L, 3)})²)`);
  def('F_rud', 'условная сила на пере', 'кН', 'РМРС ч. III, 2.2.2 (упрощённо, λ=1,75, ход вперёд)',
    ['A_rud', 'v_kn'], 'F = 0,177·A·v²·(λ+2)/3 — упрощённая оценка; полный расчёт см. решатель устройств',
    v => 0.177 * v.A_rud * v.v_kn ** 2 * (1.75 + 2) / 3,
    v => `0,177·${r(v.A_rud, 1)}·${v.v_kn}²·1,25`);

  /* === SGISC MSC.1/Circ.1627, уровень 1 === */
  def('GM_TL', 'метацентрическая высота при осадке подошвы волны', 'м',
    'SGISC 2.10.2 (pure loss of stability, L1)', ['KB', 'I_TL', 'V', 'zg'],
    'GM_min = KB + I_TL/V − z_g',
    v => v.KB + v.I_TL / v.V - v.zg, v => `${v.KB} + ${v.I_TL}/${v.V} − ${v.zg}`);
  def('dGM1', 'амплитуда изменения GM на волне', 'м', 'SGISC 2.11.2 (parametric roll, L1)',
    ['I_TH', 'I_TL', 'V'], 'δGM₁ = (I_TH − I_TL)/(2·V)',
    v => (v.I_TH - v.I_TL) / (2 * v.V), v => `(${v.I_TH} − ${v.I_TL})/(2·${v.V})`);

  /* ----- движок каскада ----- */
  function compute(id, ctx, seen) {
    seen = seen || new Set();
    if (Object.prototype.hasOwnProperty.call(ctx, id)) {
      const inp = INPUTS[id];
      return { id, title: (inp && inp[0]) || (Q[id] && Q[id].title) || id,
        unit: (inp && inp[1]) || (Q[id] && Q[id].unit) || '', value: +ctx[id],
        source: 'задано', children: [] };
    }
    const q = Q[id];
    if (!q) throw new Error(`«${id}» неизвестна и не задана в контексте; задайте значение или см. quantities()`);
    if (seen.has(id)) throw new Error('циклическая зависимость: ' + id);
    seen.add(id);
    const children = q.deps.map(dep => compute(dep, ctx, seen));
    const vals = {};
    for (const c of children) vals[c.id] = c.value;
    const value = q.f(vals);
    return { id, title: q.title, unit: q.unit, rule: q.rule, formula: q.formula,
      sub: q.sub ? q.sub(vals, value) : '', value: r(value, 4), children };
  }
  /* какие исходные данные нужны величине (транзитивно, без заданных) */
  function inputsFor(id, acc) {
    acc = acc || new Set();
    const q = Q[id];
    if (!q) { acc.add(id); return [...acc]; }
    for (const dep of q.deps) inputsFor(dep, acc);
    return [...acc];
  }
  const quantities = () => Object.values(Q).map(q =>
    ({ id: q.id, title: q.title, unit: q.unit, rule: q.rule, formula: q.formula, deps: q.deps }));
  const inputs = () => Object.entries(INPUTS).map(([id, [title, unit]]) => ({ id, title, unit }));

  return { version: '1.0', compute, inputsFor, quantities, inputs };
});
